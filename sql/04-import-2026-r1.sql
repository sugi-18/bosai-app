declare v_n int; v_a int;
begin
  select count(*) into v_n
    from respondents r
    join survey_rounds sr on sr.id = r.round_id
   where sr.label = current_setting('bosai.round_label');

  select count(*) into v_a
    from answers a
    join respondents r  on r.id = a.respondent_id
    join survey_rounds sr on sr.id = r.round_id
   where sr.label = current_setting('bosai.round_label');

  if v_n <> 64 or v_a <> 2560 then
    raise exception '取り込みが正しく行われませんでした（回答者%件・回答%件）。すべて取り消しました。', v_n, v_a;
  end if;

  raise notice '完了：64名・2,560件を登録しました';
end $$;


